/** Arabic day counts with proper agreement: يوم واحد، يومان، ٣–١٠ أيام، ١١+ يوماً. */
function arDays(n: number) {
  if (n === 1) return "يوم واحد";
  if (n === 2) return "يومان";
  if (n >= 3 && n <= 10) return `${n} أيام`;
  return `${n} يوماً`;
}

