const SAAS: Record<Lang, SaasDict> = { en, ar };

/** SaaS copy in the given language, or the request's language. */
export async function getSaasT(lang?: Lang) {
  const l = lang ?? (await (await import("./lang")).getLang());
  return { t: SAAS[l], lang: l };
}
